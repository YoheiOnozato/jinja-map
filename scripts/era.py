UNCERTAIN = ("伝", "とされる", "とされ", "という", "不詳", "不明", "諸説", "頃", "ごろ", "か")


def era_of_year(y):
    name = ERAS[0][0]
    for e, start in ERAS:
        if y >= start:
            name = e
    return name


def _year_from(text):
    """文章から (西暦年, 根拠の種類) を探す。見つからなければ (None, '')。"""
    if not text:
        return None, ""
    m = re.search(r"(?<!紀元前)(?<![0-9])(\d{3,4})年", text)
    if m and 300 <= int(m.group(1)) <= 2100:
        return int(m.group(1)), "year"
    m = _NENGO_RE.search(text)
    if m:
        n = 1 if m.group(2) == "元" else int(m.group(2))
        return NENGO[m.group(1)] + n - 1, "nengo"
    m = _NENGO_ONLY.search(text)
    if m:
        return NENGO[m.group(1)], "nengo"
    m = re.search(r"(\d{1,2})世紀", text)
    if m:
        return (int(m.group(1)) - 1) * 100 + 50, "century"
    return None, ""


def _era_from_words(text):
    for era, word in ERA_WORDS:
        if word in text:
            return era
    for name, era in EMPERORS.items():
        if name in text:
            return era
    return ""


def estimate(founded, intro="", history=""):
    """(西暦年またはNone, 時代名, 注記) を返す。時代名が空なら不明。"""
    text = founded or ""
    year, kind = _year_from(text)
    if year is not None:
        note = "伝承・推定" if any(u in text for u in UNCERTAIN) else ""
        return year, era_of_year(year), note
    era = _era_from_words(text)
    if era:
        return None, era, "伝承・推定"
    # 創建欄が空のとき：由緒文の「創建・鎮座・勧請」の近くを探す
    for src in (intro, history):
        for m in re.finditer(r"(創建|創祀|創立|鎮座|勧請|開創|草創|創始)", src or ""):
            seg = src[max(0, m.start() - 30): m.end() + 50]
            y, _ = _year_from(seg)
            if y is not None:
                return y, era_of_year(y), "伝承・推定"
            e = _era_from_words(seg)
            if e:
                return None, e, "伝承・推定"
    return None, "", ""
